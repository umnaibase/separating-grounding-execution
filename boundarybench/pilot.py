def canonical(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def sha(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def write_json(path: Path, value: object, compact: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    rendered = canonical(value) if compact else json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False)
    path.write_text(rendered + "\n", encoding="utf-8", newline="\n")


def write_jsonl(path: Path, values: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(canonical(value) + "\n" for value in values), encoding="utf-8", newline="\n")


def integrity_observations(observable: dict) -> list[dict]:
    """Only presence, ambiguity and literal identity comparisons; no semantics."""
    observations = []
    for kind, citations in sorted(observable["citations"].items()):
        for index, citation in enumerate(citations):
            retained = [source for source in observable["sources"] if source["source_id"] == citation["source_id"]]
            digests = [sha(source["text"].encode("utf-8")) for source in retained]
            observations.append({
                "citation_kind": kind, "citation_index": index,
                "source_id": citation["source_id"], "matching_retained_artifacts": len(retained),
                "source_kind_matches": [source["kind"] == kind for source in retained],
                "version_matches": [source["version"] == citation["version"] for source in retained],
                "sha256_matches": [digest == citation["sha256"] for digest in digests],
                "observed_sha256": digests,
            })
    return observations


def sanitize(case: dict) -> tuple[dict, dict]:
    identifiers = []
    for source in case["sources"]:
        if source["source_id"] not in identifiers:
            identifiers.append(source["source_id"])
    for kind in sorted(case["citations"]):
        for citation in case["citations"][kind]:
            if citation["source_id"] not in identifiers:
                identifiers.append(citation["source_id"])
    mapping = {old: f"s{index:02d}" for index, old in enumerate(identifiers, 1)}
    observable = copy.deepcopy({key: case[key] for key in ("sources", "citations", "record", "alternatives", "claims")})
    for source in observable["sources"]:
        source["source_id"] = mapping[source["source_id"]]
    for citations in observable["citations"].values():
        for citation in citations:
            citation["source_id"] = mapping[citation["source_id"]]
    observable["integrity_observations"] = integrity_observations(observable)
    return observable, mapping


def select_image_pairs(records: list[dict]) -> list[dict]:
    """Twelve cases selected by visible structure only, before reference access.

    Trace-disagreement witnesses share all other observed fields. Their selection
    makes no calculation of which trace is correct or what the policy returns.
    """
    main = sorted((r for r in records if r["collection"] == "main_reporting"), key=lambda r: r["episode_id"])
    selected, used = [], set()

    def choose(rule, predicate):
        found = next((row for row in main if row["episode_id"] not in used and predicate(row["observable"])), None)
        if found is None:
            raise ValueError("No unused image-pair candidate for " + rule)
        used.add(found["episode_id"])
        selected.append({"episode_id": found["episode_id"], "selection_rule": rule})

    def observations(value, kind=None):
        return [item for item in value["integrity_observations"] if kind is None or item["citation_kind"] == kind]

    choose("absent_cited_contract", lambda o: any(x["matching_retained_artifacts"] == 0 for x in observations(o, "contract")))
    choose("absent_cited_transactions", lambda o: any(x["matching_retained_artifacts"] == 0 for x in observations(o, "transactions")))
    choose("observed_digest_mismatch", lambda o: any(False in x["sha256_matches"] for x in observations(o)))
    choose("observed_version_mismatch", lambda o: any(False in x["version_matches"] for x in observations(o)))
    choose("source_contains_spelled_eighteen", lambda o: any("eighteen months" in s["text"] for s in o["sources"]))
    choose("multiple_distinct_contract_passages", lambda o: len({s["text"] for s in o["sources"] if s["kind"] == "contract"}) > 1)
    choose("logged_outcome_changing_intervention", lambda o: isinstance(o["record"]["override"], dict) and o["record"]["override"]["from"] != o["record"]["override"]["to"])
    choose("logged_same_valued_intervention", lambda o: isinstance(o["record"]["override"], dict) and o["record"]["override"]["from"] == o["record"]["override"]["to"])
    choose("history_not_stipulated_complete", lambda o: o["record"]["action_history_complete"] is False)
    groups = defaultdict(list)
    for row in main:
        if row["episode_id"] in used:
            continue
        material = copy.deepcopy(row["observable"])
        del material["record"]["trace"]
        groups[canonical(material)].append(row)
    witnesses = None
    for key in sorted(groups):
        rows = sorted(groups[key], key=lambda row: row["episode_id"])
        for i, left in enumerate(rows):
            for right in rows[i + 1:]:
                if left["observable"]["record"]["trace"] != right["observable"]["record"]["trace"]:
                    witnesses = (left, right)
                    break
            if witnesses:
                break
        if witnesses:
            break
    if witnesses is None:
        raise ValueError("No two unused records expose trace disagreement with all other observed fields equal")
    for index, witness in enumerate(witnesses, 1):
        used.add(witness["episode_id"])
        selected.append({"episode_id": witness["episode_id"], "selection_rule": f"trace_disagreement_witness_{index}"})
    choose("ordinary_single_numeric_contract", lambda o: (
        len([s for s in o["sources"] if s["kind"] == "contract"]) == 1
        and all(x["matching_retained_artifacts"] == 1 and all(x["version_matches"]) and all(x["sha256_matches"]) for x in observations(o))
        and not any("eighteen months" in s["text"] for s in o["sources"])
        and o["record"]["override"] is None and o["record"]["action_history_complete"] is True
    ))
    return selected


def render_sources(observable: dict, output: Path) -> dict:
    from PIL import Image, ImageDraw, ImageFont, __version__ as pillow_version
    font = ImageFont.load_default(size=16)
    width, margin, line_height = 1100, 32, 26
    measure = ImageDraw.Draw(Image.new("RGB", (width, 1), "white"))
    lines = ["RETAINED FICTIONAL SOURCE PASSAGES", ""]
    for source in observable["sources"]:
        lines.append(f"Source {source['source_id']} | kind: {source['kind']} | version: {source['version']}")
        for paragraph in source["text"].splitlines():
            current = ""
            for word in paragraph.split(" "):
                candidate = f"{current} {word}" if current else word
                if measure.textbbox((0, 0), candidate, font=font)[2] > width - 2 * margin and current:
                    lines.append(current)
                    current = word
                else:
                    current = candidate
            lines.append(current)
        lines.extend(["", ""])
    image = Image.new("RGB", (width, max(220, 2 * margin + line_height * len(lines))), "white")
    draw = ImageDraw.Draw(image)
    for index, line in enumerate(lines):
        if not line.isascii():
            raise ValueError("The fixed pilot source renderer supports ASCII passages only")
        draw.text((margin, margin + index * line_height), line, fill="black", font=font)
    output.parent.mkdir(parents=True, exist_ok=True)
    image.save(output, format="PNG", optimize=False)
    return {"library": "Pillow", "version": pillow_version, "font": "Pillow ImageFont.load_default(size=16)", "font_size": 16, "width": width, "source_format": "ASCII text rendered on a white page; PNG contains no text metadata"}


def export(data_dir: Path, output: Path, render_images: bool = False) -> dict:
    if output.exists() and any(output.iterdir()):
        raise ValueError("Refusing to replace a frozen pilot directory; export to a new empty path")
    records, join = [], []
    for collection, directory in (("main_reporting", data_dir), ("diagnostic", data_dir / "diagnostics")):
        cases = read_jsonl(directory / "cases.jsonl")
        metadata = json.loads((directory / "metadata.json").read_text(encoding="utf-8"))
        meta = {r["case_id"]: r for r in metadata["cases"]}
        for case in cases:
            if collection == "main_reporting" and meta[case["case_id"]]["split"] != "test":
                continue
            episode = "ep_" + sha((SEED + ":" + collection + ":" + case["case_id"]).encode())[:16]
            observable, source_map = sanitize(case)
            records.append({"episode_id": episode, "collection": collection, "observable": observable})
            join.append({"episode_id": episode, "collection": collection, "original_case_id": case["case_id"], "scenario_id": meta[case["case_id"]]["scenario_id"], "source_id_map": source_map})
    if len(records) != 68 or sum(r["collection"] == "main_reporting" for r in records) != 60:
        raise ValueError("Pilot requires exactly sixty reporting and eight diagnostic episodes")
    records.sort(key=lambda r: sha((SEED + ":shuffle:" + r["episode_id"]).encode()))
    paired = select_image_pairs(records)
    text_prompts = [{"episode_id": row["episode_id"], "messages": [{"role": "system", "content": PILOT_INSTRUCTIONS}, {"role": "user", "content": canonical(row["observable"])}]} for row in records]
    write_jsonl(output / "prompts/text_cases.jsonl", text_prompts)
    batches = []
    for index in range(4):
        rows = records[index * 17:(index + 1) * 17]
        relative = f"batches/text_batch_{index + 1:02d}.json"
        batch = {"batch_id": f"text_batch_{index + 1:02d}", "instructions": PILOT_INSTRUCTIONS + BATCH_INSTRUCTIONS,
                 "episodes": [{"episode_id": row["episode_id"], "observable": row["observable"]} for row in rows]}
        write_json(output / relative, batch, compact=True)
        batches.append({"path": relative, "episode_ids": [row["episode_id"] for row in rows]})
    by_episode = {row["episode_id"]: row for row in records}
    image_prompts, image_observables, renderer = [], {}, None
    for item in paired:
        episode = item["episode_id"]
        original = by_episode[episode]["observable"]
        image_relative = f"images/{episode}.png"
        if render_images:
            renderer = render_sources(original, output / image_relative)
        observable = copy.deepcopy(original)
        for source in observable["sources"]:
            del source["text"]
        observable["source_image"] = {"path": image_relative, "source_ids": [s["source_id"] for s in observable["sources"]]}
        image_observables[episode] = observable
        image_prompts.append({"episode_id": episode, "images": [image_relative], "messages": [
            {"role": "system", "content": PILOT_INSTRUCTIONS + IMAGE_INSTRUCTIONS + BATCH_INSTRUCTIONS},
            {"role": "user", "content": canonical({"episode_id": episode, "observable": observable})},
        ]})
    write_jsonl(output / "prompts/image_cases.jsonl", image_prompts)
    matched_batches, image_batches = [], []
    for index in range(2):
        episodes = [item["episode_id"] for item in paired[index * 6:(index + 1) * 6]]
        relative = f"batches/paired_text_batch_{index + 1:02d}.json"
        write_json(output / relative, {
            "batch_id": f"paired_text_batch_{index + 1:02d}",
            "instructions": PILOT_INSTRUCTIONS + BATCH_INSTRUCTIONS,
            "episodes": [{"episode_id": episode, "observable": by_episode[episode]["observable"]} for episode in episodes],
        }, compact=True)
        matched_batches.append({"path": relative, "episode_ids": episodes})
        image_relative = f"batches/image_batch_{index + 1:02d}.json"
        write_json(output / image_relative, {
            "batch_id": f"image_batch_{index + 1:02d}",
            "instructions": PILOT_INSTRUCTIONS + IMAGE_INSTRUCTIONS + BATCH_INSTRUCTIONS,
            "episodes": [{"episode_id": episode, "observable": image_observables[episode], "image": f"images/{episode}.png"} for episode in episodes],
        }, compact=True)
        image_batches.append({"path": image_relative, "episode_ids": episodes})
    write_json(output / "join_map.json", {"protocol": PROTOCOL, "records": sorted(join, key=lambda x: x["episode_id"])})
    selection = {"protocol": PROTOCOL, "seed": SEED, "main_reporting_episodes": 60, "diagnostic_episodes": 8,
                 "text_batches": batches, "paired_text_batches": matched_batches, "image_batches": image_batches, "paired_image_episodes": paired,
                 "failure_policy": FAILURE_POLICY,
                 "batch_context": "Seventeen episodes share each primary-text context; six episodes share each matched-text/image context. No per-episode isolation is claimed.",
                 "metric_plan": ["Report main60 and diagnostic8 separately.", "Report c1 lineage separately from the other six reasoning scopes.", "Compare matched six-episode-batch text12 with image12; do not use original seventeen-episode text batches for the paired comparison.", "Report image source-grounding scopes c2/c3 separately (24 claims).", "Preserve denominators and report conversion failures plus failure-adjusted agreement."],
                 "selection_basis": "Observable structure and literal equality only; reference labels, construction subtype metadata and checker predictions were not accessed. Trace witnesses differ in their observed traces without a calculation of which trace is correct.",
                 "renderer": renderer, "images_rendered": render_images}
    write_json(output / "selection.json", selection)
    write_json(output / "model_run.example.json", {"protocol": PROTOCOL, "status": "not_run", "run_id": "assistant-pilot-1", "model_display_name": "Codex assistant (GPT-6 family as described by session)", "exact_model_snapshot": None, "sampling_parameters": None,
        "author_model_relationship": "same assistant system as artifact author; not independent evaluation", "batch_context": "Record whether each batch used a fresh context", "permitted_tool_access": ["read named input batch", "view named PNG for image condition", "write literal model response"], "tool_trace_files": [], "limitations": ["Exact model snapshot and sampling parameters are not exposed by this interface."]})
    files = {str(path.relative_to(output)): {"sha256": sha(path.read_bytes()), "bytes": path.stat().st_size} for path in sorted(output.rglob("*")) if path.is_file()}
    manifest = {"protocol": PROTOCOL, "seed": SEED, "files": files,
                "source_corpus_sha256": {str(path.relative_to(data_dir)): sha(path.read_bytes()) for path in (data_dir / "cases.jsonl", data_dir / "metadata.json", data_dir / "diagnostics/cases.jsonl", data_dir / "diagnostics/metadata.json")},
                "no_model_invoked": True, "no_reference_labels_read": True}
    write_json(output / "manifest.json", manifest)
    return selection


def verify_frozen(pilot_dir: Path) -> dict:
    manifest = json.loads((pilot_dir / "manifest.json").read_text(encoding="utf-8"))
    for relative, expected in manifest["files"].items():
        path = pilot_dir / relative
        if sha(path.read_bytes()) != expected["sha256"] or path.stat().st_size != expected["bytes"]:
            raise ValueError("Frozen pilot input mismatch: " + relative)
    return manifest


def _responses(directory: Path, expected: dict[str, dict], schedule: list[dict]) -> tuple[dict, dict, list[dict]]:
    """Apply the frozen entire-batch failure rule without repairing raw output."""
    observations, hashes, failures = {}, {}, []
    scheduled_files = {Path(batch["path"]).name for batch in schedule}
    extras = {path.name for path in directory.glob("*.json")} - scheduled_files
    if extras:
        raise ValueError("Unscheduled response files are not accepted: " + ", ".join(sorted(extras)))
    for batch in schedule:
        filename = Path(batch["path"]).name
        path = directory / filename
        episodes = batch["episode_ids"]
        hashes[filename] = sha(path.read_bytes()) if path.is_file() else None
        parsed = {}
        try:
            def unique_object(pairs):
                result = {}
                for key, value in pairs:
                    if key in result:
                        raise ValueError("Duplicate JSON object key: " + key)
                    result[key] = value
                return result
            payload = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_object)
            if not isinstance(payload, dict) or set(payload) != {"episodes"} or not isinstance(payload["episodes"], list):
                raise ValueError("Raw model output must have exactly one episodes list")
            for row in payload["episodes"]:
                if not isinstance(row, dict) or set(row) != {"episode_id", "claims"}:
                    raise ValueError("Every episode object must contain exactly episode_id and claims")
                episode = row["episode_id"]
                if not isinstance(episode, str) or episode not in episodes or episode in parsed:
                    raise ValueError("Unknown, misplaced or repeated pilot episode")
                claims = row["claims"]
                if not isinstance(claims, list) or len(claims) != 7:
                    raise ValueError("Every model response must contain seven claims")
                observed = {}
                for claim in claims:
                    if not isinstance(claim, dict) or set(claim) != {"claim_id", "kind", "label", "check", "evidence"}:
                        raise ValueError("Every claim requires exactly claim_id, kind, label, check and evidence")
                    cid = claim["claim_id"]
                    if not isinstance(cid, str) or cid in observed or cid not in expected[episode]:
                        raise ValueError("Unknown or repeated pilot claim")
                    if claim["kind"] != expected[episode][cid] or claim["label"] not in ("supported", "contradicted", "unresolved"):
                        raise ValueError("Invalid pilot claim kind or label")
                    if not isinstance(claim["check"], str) or not claim["check"].strip() or not isinstance(claim["evidence"], list) or any(not isinstance(item, str) for item in claim["evidence"]):
                        raise ValueError("A model claim needs its literal reason and evidence list")
                    observed[cid] = {**claim, "conversion_failure": False}
                parsed[episode] = {"episode_id": episode, "claims": list(observed.values())}
            if set(parsed) != set(episodes):
                raise ValueError("Raw batch does not cover every scheduled episode exactly once")
        except (ValueError, OSError, TypeError, KeyError) as error:
            failures.append({"file": filename, "reason": str(error), "episode_ids": episodes, "claims_converted": 7 * len(episodes)})
            parsed = {episode: {"episode_id": episode, "claims": [
                {"claim_id": cid, "kind": kind, "label": "unresolved", "check": "Whole-batch conversion failure; this is not a model classification.", "evidence": [], "conversion_failure": True}
                for cid, kind in expected[episode].items()
            ]} for episode in episodes}
        observations.update(parsed)
    if set(observations) != set(expected):
        raise ValueError("Frozen schedule and selected episode set differ")
    return observations, hashes, failures


def score_pilot(pilot_dir: Path, data_dir: Path, raw_text: Path, output: Path,
                run_metadata: Path, raw_image: Path | None = None,
                raw_paired_text: Path | None = None) -> dict:
    from .evaluation import score, metrics, validate, validate_diagnostics
    manifest = verify_frozen(pilot_dir)
    for relative, expected in manifest["source_corpus_sha256"].items():
        if sha((data_dir / relative).read_bytes()) != expected:
            raise ValueError("Source corpus changed after prompt freeze: " + relative)
    run = json.loads(run_metadata.read_text(encoding="utf-8"))
    if run.get("status") != "completed" or not run.get("run_id") or not run.get("model_display_name"):
        raise ValueError("Supply completed model-run provenance, not the unrun example")
    prompts = read_jsonl(pilot_dir / "prompts/text_cases.jsonl")
    observables = {row["episode_id"]: json.loads(row["messages"][1]["content"]) for row in prompts}
    expected = {episode: {c["claim_id"]: c["kind"] for c in observable["claims"]} for episode, observable in observables.items()}
    selected = json.loads((pilot_dir / "selection.json").read_text(encoding="utf-8"))
    text, text_hashes, text_failures = _responses(raw_text, expected, selected["text_batches"])
    paired_ids = {row["episode_id"] for row in selected["paired_image_episodes"]}
    paired_expected = {key: expected[key] for key in paired_ids}
    if raw_image is not None and raw_paired_text is None:
        raise ValueError("The image comparison requires the matched six-case-batch text run")
    paired_text, paired_text_hashes, paired_text_failures = ({}, {}, []) if raw_paired_text is None else _responses(raw_paired_text, paired_expected, selected["paired_text_batches"])
    image, image_hashes, image_failures = ({}, {}, []) if raw_image is None else _responses(raw_image, paired_expected, selected["image_batches"])
    join = {row["episode_id"]: row for row in json.loads((pilot_dir / "join_map.json").read_text(encoding="utf-8"))["records"]}
    source_data = {}
    validate(data_dir)
    validate_diagnostics(data_dir / "diagnostics")
    for name, directory in (("main_reporting", data_dir), ("diagnostic", data_dir / "diagnostics")):
        source_data[name] = {
            "cases": {row["case_id"]: row for row in read_jsonl(directory / "cases.jsonl")},
            "refs": {row["case_id"]: row for row in read_jsonl(directory / "reference.jsonl")},
            "metadata": {row["case_id"]: row for row in json.loads((directory / "metadata.json").read_text(encoding="utf-8"))["cases"]},
        }

    def augmented_metrics(rows):
        values = metrics(rows)
        failed = [row for row in rows if row["conversion_failure"]]
        adjusted_correct = sum(row["prediction"] == row["reference"] and not row["conversion_failure"] for row in rows)
        values.update({"ordinary_label_agreement": values["accuracy"],
                       "failure_adjusted_correct": adjusted_correct,
                       "failure_adjusted_agreement": adjusted_correct / len(rows) if rows else None,
                       "conversion_failure_claims": len(failed),
                       "conversion_failure_episodes": len({row["case_id"] for row in failed})})
        return values

    def scored_subset(responses, episode_ids, method):
        predictions, references, cases, metadata, rows = [], [], [], [], []
        for episode in sorted(episode_ids):
            provenance = join[episode]
            cid, collection = provenance["original_case_id"], provenance["collection"]
            data = source_data[collection]
            predictions.append({"case_id": cid, "method": method, "claims": responses[episode]["claims"]})
            references.append(data["refs"][cid])
            cases.append(data["cases"][cid])
            metadata.append(data["metadata"][cid])
            for claim in responses[episode]["claims"]:
                rows.append({"case_id": cid, "scenario_id": provenance["scenario_id"], "kind": claim["kind"],
                             "prediction": claim["label"], "reference": data["refs"][cid]["labels"][claim["claim_id"]],
                             "conversion_failure": claim["conversion_failure"],
                             **{key: data["metadata"][cid][key] for key in ("split", "variant")}})
        result = score(predictions, references, {"cases": metadata}, cases)
        result["experiment_type"] = "same-assistant tool-assisted pilot on authored fixtures"
        result["pilot_protocol"] = PROTOCOL
        result["primary_metric"] = "failure_adjusted_agreement; converted claims count as incorrect even when reference is unresolved"
        group = result["methods"][method]
        group["all"] = augmented_metrics(rows)
        for group_name, field in (("by_kind", "kind"), ("by_split", "split"), ("by_variant", "variant"), ("by_scenario", "scenario_id")):
            group[group_name] = {key: augmented_metrics([row for row in rows if row[field] == key]) for key in group[group_name]}
        group["test_by_kind"] = {kind: augmented_metrics([row for row in rows if row["split"] == "test" and row["kind"] == kind]) for kind in CLAIM_KINDS}
        group["scope_groups"] = {
            "lineage_c1": augmented_metrics([row for row in rows if row["kind"] == "contract_lineage"]),
            "six_reasoning_scopes": augmented_metrics([row for row in rows if row["kind"] != "contract_lineage"]),
            "source_grounding_c2_c3": augmented_metrics([row for row in rows if row["kind"] in ("commitment_grounding", "dispute_grounding")]),
        }
        return result

    main_ids = {episode for episode, row in join.items() if row["collection"] == "main_reporting"}
    diagnostic_ids = set(join) - main_ids
    reports = {
        "main_reporting": scored_subset(text, main_ids, "assistant_text"),
        "diagnostics": scored_subset(text, diagnostic_ids, "assistant_text"),
    }
    if paired_text:
        reports["paired_text"] = scored_subset(paired_text, paired_ids, "assistant_matched_text")
    if image:
        reports["paired_image"] = scored_subset(image, paired_ids, "assistant_image_sources")
    # This small observable subgroup is descriptive, not a new tuned benchmark.
    spelling_ids = {episode for episode in main_ids if any("eighteen months" in s["text"] for s in observables[episode]["sources"])}
    spelling_rows = []
    for episode in sorted(spelling_ids):
        provenance = join[episode]
        cid = provenance["original_case_id"]
        pred = next(c for c in text[episode]["claims"] if c["kind"] == "commitment_grounding")
        truth = source_data["main_reporting"]["refs"][cid]["labels"][pred["claim_id"]]
        spelling_rows.append({"case_id": cid, "scenario_id": provenance["scenario_id"], "reference": truth, "prediction": pred["label"], "conversion_failure": pred["conversion_failure"]})
    differences = []
    for episode in sorted(image):
        left, right = {c["claim_id"]: c for c in paired_text[episode]["claims"]}, {c["claim_id"]: c for c in image[episode]["claims"]}
        for cid in left:
            if left[cid]["label"] != right[cid]["label"]:
                differences.append({"episode_id": episode, "claim_id": cid, "kind": left[cid]["kind"], "text_label": left[cid]["label"], "image_label": right[cid]["label"], "text_conversion_failure": left[cid]["conversion_failure"], "image_conversion_failure": right[cid]["conversion_failure"]})
    summary = {"protocol": PROTOCOL, "model_run": run, "model_run_sha256": sha(run_metadata.read_bytes()), "prompt_manifest_sha256": sha((pilot_dir / "manifest.json").read_bytes()),
               "raw_response_sha256": {"text": text_hashes, "paired_text": paired_text_hashes, "image": image_hashes},
               "conversion_failures": {"text": text_failures, "paired_text": paired_text_failures, "image": image_failures},
               "failure_policy": selected["failure_policy"],
               "reports": reports,
               "spelled_eighteen_commitment_claims": {"episode_ids": sorted(spelling_ids), "metrics": augmented_metrics(spelling_rows)},
               "paired_label_disagreements": differences if image else None,
               "limitations": ["Same assistant system as author; not independent annotation or blind model selection.", "Exact model identity and sampling settings may be unavailable; use archived run metadata.", "Tool-assisted citation integrity; no tool computed model claim labels.", "Seventeen episodes share each primary-text context; six share each matched-text or image context. No per-case isolation is claimed.", "Images render the same source passages with the populated record unchanged; this is not an extraction accuracy experiment.", "Tool restrictions are instructions with worker-reported protocol compliance; complete tool traces were not independently audited, not a technical sandbox.", "These are designed fixtures, not a sampled financial deployment population."]}
    for name, report in reports.items():
        write_json(output / name / "summary.json", report)
    write_json(output / "paired_differences.json", {"image_condition_completed": bool(image), "differences": differences if image else None})
    write_json(output / "summary.json", summary)
    lines = ["# Archived assistant pilot", "", "All figures below are scored from archived literal assistant outputs. Conditions and corpora remain separate; no combined 68-episode accuracy is reported.", "",
             "| Corpus / condition | Episodes | Claims | Failure-adjusted agreement | Ordinary agreement | Failed claims | False support / endorsements |", "|---|---:|---:|---:|---:|---:|---:|"]
    for name, report in reports.items():
        group = next(iter(report["methods"].values()))["all"]
        lines.append(f"| {name} | {group['episodes']} | {group['claims']} | {100*group['failure_adjusted_agreement']:.2f}% | {100*group['ordinary_label_agreement']:.2f}% | {group['conversion_failure_claims']} | {group['false_support_count']} / {group['endorsements']} |")
    lines.extend(["", "## Helper-sensitive and reasoning scopes", "", "| Corpus / condition | Scope | Claims | Failure-adjusted agreement | Failed claims | False support |", "|---|---|---:|---:|---:|---:|"])
    for name, report in reports.items():
        for scope, group in next(iter(report["methods"].values()))["scope_groups"].items():
            lines.append(f"| {name} | {scope} | {group['claims']} | {100*group['failure_adjusted_agreement']:.2f}% | {group['conversion_failure_claims']} | {group['false_support_count']} |")
    lines.extend(["", "## Claims by kind", "", "| Corpus / condition | Kind | Claims | Failure-adjusted agreement | Failed claims | False support |", "|---|---|---:|---:|---:|---:|"])
    for name, report in reports.items():
        for kind, group in next(iter(report["methods"].values()))["by_kind"].items():
            lines.append(f"| {name} | {kind} | {group['claims']} | {100*group['failure_adjusted_agreement']:.2f}% | {group['conversion_failure_claims']} | {group['false_support_count']} |")
    wording = summary["spelled_eighteen_commitment_claims"]["metrics"]
    lines.extend(["", f"The pre-existing reporting-source subgroup containing the phrase ‘eighteen months’ has {wording['claims']} commitment-grounding claims; its failure-adjusted agreement is {100*wording['failure_adjusted_agreement']:.2f}% and false-support count is {wording['false_support_count']}. This is reported separately because it lies beyond the released checker's numeric source grammar.", ""])
    lines.extend(["Malformed or missing batches are converted wholly to unresolved, marked as conversion failures, and retained in the denominator. Every converted claim counts as incorrect in the primary failure-adjusted measure, including when its reference is unresolved. Ordinary three-label agreement is secondary; raw files are neither repaired nor retried.", ""])
    lines.extend(["Limitations: " + " ".join(summary["limitations"]), ""])
    (output / "summary.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return summary


